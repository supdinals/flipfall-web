/** Parse one level's map into world geometry in pixel coordinates. */
export function buildLevel(index) {
  const def = LEVELS[index];
  const solids = [];
  const spikes = [];
  const stars = [];
  const crumbles = [];
  const gates = [];
  let spawn = { x: TILE * 2, y: TILE * 15 };
  let portal = { x: TILE * 28, y: TILE * 16 };

  def.map.forEach((row, rowIndex) => {
    [...row].forEach((cell, colIndex) => {
      const x = colIndex * TILE;
      const y = rowIndex * TILE;
      if (cell === '#') solids.push({ x, y, w: TILE, h: TILE, kind: 'solid' });
      else if (cell === '^') spikes.push({ x, y, w: TILE, h: TILE, pointsUp: true });
      else if (cell === 'v') spikes.push({ x, y, w: TILE, h: TILE, pointsUp: false });
      else if (cell === 'C') crumbles.push({ x, y, w: TILE, h: TILE, kind: 'crumble', state: 'idle', timer: 0 });
      else if (cell === 'G') gates.push({ x, y, w: TILE, h: TILE, kind: 'gate' });
      else if (cell === '*') stars.push({ x: x + 8, y: y + 8, w: 24, h: 24, taken: false, phase: (colIndex * 0.7 + rowIndex) % 6.28 });
      else if (cell === 'S') spawn = { x: x + 5, y: y + 2 };
      else if (cell === 'X') portal = { x, y };
    });
  });

  const movers = def.movers.map((m) => ({
    x: m.x, y: m.y, w: 84, h: 18, kind: 'mover',
    axis: m.axis, range: m.range, speed: m.speed, phase: m.phase,
    baseX: m.x, baseY: m.y, dx: 0, dy: 0, t: m.phase * Math.PI * 2,
  }));

  return {
    index,
    name: def.name,
    hint: def.hint,
    solids, spikes, stars, crumbles, gates, movers, spawn, portal,
    starTotal: stars.length,
  };
}

export const LEVEL_COUNT = LEVELS.length;
export function levelName(index) {
  return LEVELS[index].name;
}
